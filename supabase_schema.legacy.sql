-- Supabase Schema for Flat Rent Manager

-- Enable pgcrypto for password hashing
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

-- 1. Profiles Table
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username TEXT UNIQUE,
  name TEXT DEFAULT '',
  role TEXT DEFAULT 'user',
  "createdAt" TIMESTAMPTZ DEFAULT now(),
  "updatedAt" TIMESTAMPTZ DEFAULT now()
);

-- 2. Buildings Table
CREATE TABLE IF NOT EXISTS public.buildings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  "buildingName" TEXT NOT NULL,
  address TEXT DEFAULT '',
  area TEXT DEFAULT '',
  "caretakerName" TEXT DEFAULT '',
  "caretakerPhone" TEXT DEFAULT '',
  "securityPhone" TEXT DEFAULT '',
  "createdAt" TIMESTAMPTZ DEFAULT now(),
  "updatedAt" TIMESTAMPTZ DEFAULT now()
);

-- 3. Flats Table
CREATE TABLE IF NOT EXISTS public.flats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  "buildingId" BIGINT NOT NULL REFERENCES public.buildings(id) ON DELETE CASCADE,
  "flatNumber" TEXT NOT NULL,
  floor TEXT DEFAULT '',
  "monthlyRent" DOUBLE PRECISION DEFAULT 0,
  status TEXT DEFAULT 'vacant',
  "createdAt" TIMESTAMPTZ DEFAULT now(),
  "updatedAt" TIMESTAMPTZ DEFAULT now()
);

-- 4. Tenants Table
CREATE TABLE IF NOT EXISTS public.tenants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  phone2 TEXT DEFAULT '',
  "ksebNo" TEXT DEFAULT '',
  address TEXT DEFAULT '',
  "idProof" TEXT DEFAULT '',
  documents JSONB DEFAULT '[]'::jsonb,
  amenities JSONB DEFAULT '[]'::jsonb,
  "createdAt" TIMESTAMPTZ DEFAULT now(),
  "updatedAt" TIMESTAMPTZ DEFAULT now()
);

-- 5. Leases Table
CREATE TABLE IF NOT EXISTS public.leases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  "tenantId" BIGINT NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
  "flatId" BIGINT NOT NULL REFERENCES public.flats(id) ON DELETE CASCADE,
  "leaseStart" TEXT NOT NULL,
  "leaseEnd" TEXT NOT NULL,
  "monthlyRent" DOUBLE PRECISION DEFAULT 0,
  "advanceMonths" DOUBLE PRECISION DEFAULT 0,
  "securityDeposit" DOUBLE PRECISION DEFAULT 0,
  "moveOutDate" TEXT,
  "createdAt" TIMESTAMPTZ DEFAULT now(),
  "updatedAt" TIMESTAMPTZ DEFAULT now()
);

-- 6. Rent Payments Table
CREATE TABLE IF NOT EXISTS public.rent_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  "leaseId" BIGINT NOT NULL REFERENCES public.leases(id) ON DELETE CASCADE,
  month INTEGER NOT NULL,
  year INTEGER NOT NULL,
  amount DOUBLE PRECISION DEFAULT 0,
  "amountPaid" DOUBLE PRECISION DEFAULT 0,
  balance DOUBLE PRECISION DEFAULT 0,
  "paymentDate" TEXT NOT NULL,
  "paymentMethod" TEXT DEFAULT 'Cash',
  status TEXT DEFAULT 'not_paid',
  settled BOOLEAN DEFAULT false,
  discount DOUBLE PRECISION DEFAULT 0,
  "createdAt" TIMESTAMPTZ DEFAULT now(),
  "updatedAt" TIMESTAMPTZ DEFAULT now()
);

-- 7. Payment Allocations Table
CREATE TABLE IF NOT EXISTS public.payment_allocations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  "paymentId" BIGINT NOT NULL REFERENCES public.rent_payments(id) ON DELETE CASCADE,
  "leaseId" BIGINT NOT NULL REFERENCES public.leases(id) ON DELETE CASCADE,
  month INTEGER NOT NULL,
  year INTEGER NOT NULL,
  "allocatedAmount" DOUBLE PRECISION DEFAULT 0
);

-- Indices
CREATE INDEX IF NOT EXISTS idx_buildings_user ON public.buildings(user_id);
CREATE INDEX IF NOT EXISTS idx_flats_user ON public.flats(user_id);
CREATE INDEX IF NOT EXISTS idx_tenants_user ON public.tenants(user_id);
CREATE INDEX IF NOT EXISTS idx_leases_user ON public.leases(user_id);
CREATE INDEX IF NOT EXISTS idx_rent_payments_user ON public.rent_payments(user_id);

