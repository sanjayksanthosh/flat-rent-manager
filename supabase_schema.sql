-- 4. Admin API — user management without ever touching Supabase Auth
-- ----------------------------------------------------------------------------

create or replace function public.app_admin_list_users()
returns table (
  id                   bigint,
  username             text,
  name                 text,
  role                 text,
  is_active            boolean,
  must_change_password boolean,
  last_login_at        timestamptz,
  created_at           timestamptz
)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  perform app.require_admin();

  return query
    select u.id, u.username, u.name, u.role, u.is_active,
           u.must_change_password, u.last_login_at, u.created_at
      from public.app_users u
     order by u.id;
end;
$$;

create or replace function public.app_admin_create_user(
  p_username text,
  p_password text,
  p_name     text default '',
  p_role     text default 'user'
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_admin bigint := app.require_admin();
  v_role  text   := coalesce(nullif(trim(p_role), ''), 'user');
  v_id    bigint;
begin
  perform app.assert_username(trim(p_username));
  perform app.assert_password(p_password);

  if v_role not in ('admin', 'user') then
    raise exception 'Invalid role' using errcode = '22023';
  end if;

  begin
    insert into public.app_users (username, password_hash, name, role)
    values (
      trim(p_username),
      extensions.crypt(p_password, extensions.gen_salt('bf', 12)),
      coalesce(p_name, ''),
      v_role
    )
    returning id into v_id;
  exception when unique_violation then
    raise exception 'Username "%" is already taken', trim(p_username) using errcode = '23505';
  end;

  return jsonb_build_object(
    'id', v_id,
    'username', trim(p_username),
    'name', coalesce(p_name, ''),
    'role', v_role
  );
end;
$$;

create or replace function public.app_admin_update_user(
  p_id        bigint,
  p_name      text    default null,
  p_role      text    default null,
  p_password  text    default null,
  p_is_active boolean default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_admin bigint := app.require_admin();
  v_user  public.app_users;
begin
  select * into v_user from public.app_users where id = p_id;

  if not found then
    raise exception 'User not found' using errcode = 'P0002';
  end if;

  if p_role is not null and p_role not in ('admin', 'user') then
    raise exception 'Invalid role' using errcode = '22023';
  end if;

  if p_id = v_admin and p_role is not null and p_role <> 'admin' then
    raise exception 'You cannot remove your own admin role' using errcode = '22023';
  end if;

  if p_id = v_admin and p_is_active is false then
    raise exception 'You cannot disable your own account' using errcode = '22023';
  end if;

  if p_password is not null then
    perform app.assert_password(p_password);
  end if;

  update public.app_users
     set name                 = coalesce(p_name, name),
         role                 = coalesce(p_role, role),
         is_active            = coalesce(p_is_active, is_active),
         password_hash        = case when p_password is null then password_hash
                                     else extensions.crypt(p_password, extensions.gen_salt('bf', 12)) end,
         password_changed_at  = case when p_password is null then password_changed_at else now() end,
         must_change_password = case when p_password is null then must_change_password else false end,
         failed_attempts      = case when p_password is null then failed_attempts else 0 end,
         locked_until         = case when p_password is null then locked_until else null end,
         updated_at           = now()
   where id = p_id;

  -- A password reset or a disabled account kills every open session.
  if p_password is not null or p_is_active is false then
    update public.app_sessions
       set revoked_at = now()
     where user_id = p_id
       and revoked_at is null;
  end if;

  select * into v_user from public.app_users where id = p_id;

  return jsonb_build_object(
    'id', v_user.id,
    'username', v_user.username,
    'name', v_user.name,
    'role', v_user.role,
    'is_active', v_user.is_active
  );
end;
$$;

create or replace function public.app_admin_delete_user(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_admin bigint := app.require_admin();
  v_role  text;
begin
  if p_id = v_admin then
    raise exception 'You cannot delete your own account' using errcode = '22023';
  end if;

  select u.role into v_role from public.app_users u where u.id = p_id;

  if v_role is null then
    raise exception 'User not found' using errcode = 'P0002';
  end if;

  if v_role = 'admin'
     and (select count(*) from public.app_users u where u.role = 'admin' and u.is_active) <= 1 then
    raise exception 'Cannot delete the last admin' using errcode = '22023';
  end if;

  -- Sessions and every owned row cascade away with the user.
  delete from public.app_users where id = p_id;
end;
$$;

-- ----------------------------------------------------------------------------
-- 5. Migrate the old Supabase-Auth data model (uuid user_id -> bigint)
-- ----------------------------------------------------------------------------
-- Old policies reference user_id and auth.uid(); drop them before the column
-- type changes. New ones are created in section 6.
do $$
declare
  r record;
begin
  for r in
    select tablename, policyname
      from pg_policies
     where schemaname = 'public'
       and tablename in ('buildings', 'flats', 'tenants', 'leases',
                         'rent_payments', 'payment_allocations', 'profiles')
  loop
    execute format('drop policy if exists %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

do $$
declare
  t          text;
  v_has_rows boolean;
begin
  -- This block depends on section 1. If the file was only partially run, say so
  -- plainly instead of failing with "relation public.app_users does not exist".
  if to_regclass('public.app_users') is null then
    raise exception
      'public.app_users does not exist. Run the WHOLE supabase_schema.sql from the first line to the last in one go (select all, then run).';
  end if;

  foreach t in array array['buildings', 'flats', 'tenants', 'leases',
                           'rent_payments', 'payment_allocations']
  loop
    -- A fresh project may not have the data tables yet; the legacy schema
    -- creates them. Skip rather than abort the whole script.
    if to_regclass(format('public.%I', t)) is null then
      raise notice 'skipping public.%: table does not exist', t;
      continue;
    end if;

    if exists (
      select 1
        from information_schema.columns
       where table_schema = 'public'
         and table_name = t
         and column_name = 'user_id'
         and data_type = 'uuid'
    ) then
      execute format('select exists (select 1 from public.%I)', t) into v_has_rows;

      if v_has_rows then
        raise exception
          'Table % already contains rows owned by Supabase Auth users. Back the data up and migrate user_id by hand before running this script.', t;
      end if;

      execute format('alter table public.%I drop column user_id', t);
    end if;

    if not exists (
      select 1
        from information_schema.columns
       where table_schema = 'public'
         and table_name = t
         and column_name = 'user_id'
    ) then
      execute format(
        'alter table public.%I add column user_id bigint not null references public.app_users(id) on delete cascade',
        t
      );
    end if;

    execute format('create index if not exists idx_%s_user on public.%I(user_id)', t, t);
  end loop;
end $$;

-- ----------------------------------------------------------------------------
-- 6. Row level security — ownership comes from the request token
-- ----------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array['buildings', 'flats', 'tenants', 'leases',
                           'rent_payments', 'payment_allocations']
  loop
    if to_regclass(format('public.%I', t)) is null then
      raise notice 'skipping RLS for public.%: table does not exist', t;
      continue;
    end if;

    execute format('alter table public.%I enable row level security', t);

    execute format('drop policy if exists %I on public.%I', t || '_select_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_update_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_delete_own', t);

    execute format(
      'create policy %I on public.%I for select to anon, authenticated
         using (user_id = app.session_user_id())', t || '_select_own', t);

    execute format(
      'create policy %I on public.%I for insert to anon, authenticated
         with check (user_id = app.session_user_id())', t || '_insert_own', t);

    execute format(
      'create policy %I on public.%I for update to anon, authenticated
         using (user_id = app.session_user_id())
         with check (user_id = app.session_user_id())', t || '_update_own', t);

    execute format(
      'create policy %I on public.%I for delete to anon, authenticated
         using (user_id = app.session_user_id())', t || '_delete_own', t);

    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', t);
  end loop;
end $$;

