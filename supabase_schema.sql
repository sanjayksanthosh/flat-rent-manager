-- ============================================================================
-- Flat Rent Manager — database-native authentication
-- ----------------------------------------------------------------------------
-- No Supabase Auth, no email addresses. Users are identified by a username and
-- a bcrypt password hash that lives in this database.
--
-- How it works
--   1. app_login(username, password) verifies the bcrypt hash, opens a row in
--      app_sessions and returns a 256-bit random token. Only the SHA-256 of
--      that token is stored, so a database leak does not leak live sessions.
--   2. The client sends the token on every request in the `x-app-token`
--      header. PostgREST exposes headers to Postgres via
--      current_setting('request.headers'), and app.session_user_id() turns the
--      token back into a user id.
--   3. Row level security compares user_id against app.session_user_id(),
--      so the token is the only thing that grants access to a user's rows.
--
-- Run this whole file in the Supabase SQL editor. It is idempotent and also
-- migrates a database created by the old supabase_schema.legacy.sql.
-- ============================================================================

create extension if not exists pgcrypto with schema extensions;
create schema if not exists app;

-- ----------------------------------------------------------------------------
-- 1. Users and sessions
-- ----------------------------------------------------------------------------
create table if not exists public.app_users (
  id                   bigint generated by default as identity primary key,
  username             text        not null,
  password_hash        text        not null,
  name                 text        not null default '',
  role                 text        not null default 'user' check (role in ('admin', 'user')),
  is_active            boolean     not null default true,
  must_change_password boolean     not null default false,
  failed_attempts      integer     not null default 0,
  locked_until         timestamptz,
  last_login_at        timestamptz,
  password_changed_at  timestamptz not null default now(),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

-- Usernames are case-insensitive: "Admin" and "admin" are the same account.
create unique index if not exists app_users_username_lower_key
  on public.app_users (lower(username));

create table if not exists public.app_sessions (
  id           uuid        primary key default gen_random_uuid(),
  user_id      bigint      not null references public.app_users(id) on delete cascade,
  token_hash   text        not null unique,
  issued_at    timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  expires_at   timestamptz not null,
  revoked_at   timestamptz,
  user_agent   text
);

create index if not exists idx_app_sessions_user on public.app_sessions(user_id);

-- Password hashes and live sessions are never exposed through the REST API.
-- Only the SECURITY DEFINER functions below can read these tables.
alter table public.app_users enable row level security;
alter table public.app_sessions enable row level security;
revoke all on public.app_users from anon, authenticated;
revoke all on public.app_sessions from anon, authenticated;

-- ----------------------------------------------------------------------------
-- 2. Helpers (private schema, not exposed by PostgREST)
-- ----------------------------------------------------------------------------

-- SHA-256 of the token presented in the request header, or '' when absent.
create or replace function app.request_token_hash()
returns text
language sql
stable
as $$
  select encode(
           extensions.digest(
             coalesce(
               nullif(current_setting('request.headers', true), '')::json ->> 'x-app-token',
               ''
             ),
             'sha256'
           ),
           'hex'
         );
$$;

-- The user id behind the request token, or NULL when there is no valid session.
create or replace function app.session_user_id()
returns bigint
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select s.user_id
    from public.app_sessions s
   where s.revoked_at is null
     and s.expires_at > now()
     and s.token_hash = app.request_token_hash()
   limit 1;
$$;

create or replace function app.session_user_role()
returns text
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select u.role
    from public.app_users u
   where u.id = app.session_user_id()
     and u.is_active;
$$;

-- Raises unless the caller is an active admin; returns the admin's id.
create or replace function app.require_admin()
returns bigint
language plpgsql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_id   bigint := app.session_user_id();
  v_role text;
begin
  if v_id is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  select u.role into v_role
    from public.app_users u
   where u.id = v_id and u.is_active;

  if v_role is distinct from 'admin' then
    raise exception 'Admin access required' using errcode = '42501';
  end if;

  return v_id;
end;
$$;

create or replace function app.assert_username(p_username text)
returns void
language plpgsql
immutable
as $$
begin
  if p_username is null or p_username !~ '^[A-Za-z0-9._-]{3,32}$' then
    raise exception 'Username must be 3-32 characters (letters, numbers, dot, dash or underscore)'
      using errcode = '22023';
  end if;
end;
$$;

-- No length or complexity rules on purpose: any password the admin types is
-- accepted. The single guard is "not blank", so an empty form field cannot
-- silently create an account with an empty password.
create or replace function app.assert_password(p_password text)
returns void
language plpgsql
immutable
as $$
begin
  if p_password is null or length(p_password) = 0 then
    raise exception 'Password cannot be empty' using errcode = '22023';
  end if;
end;
$$;

-- ----------------------------------------------------------------------------
-- 3. Auth API (exposed through PostgREST as /rest/v1/rpc/<name>)
-- ----------------------------------------------------------------------------

create or replace function public.app_login(p_username text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_user  public.app_users;
  v_token text;
begin
  if p_username is null or p_password is null or length(trim(p_username)) = 0 then
    return jsonb_build_object(
      'ok', false, 'code', 'invalid_request',
      'error', 'Username and password are required');
  end if;

  -- Opportunistic cleanup so the session table does not grow forever.
  delete from public.app_sessions where expires_at < now() - interval '30 days';

  select * into v_user
    from public.app_users
   where lower(username) = lower(trim(p_username));

  if not found then
    -- Spend roughly the same time as a real bcrypt check so an attacker cannot
    -- tell "unknown user" from "wrong password" by timing the response.
    perform extensions.crypt(p_password, extensions.gen_salt('bf', 12));
    return jsonb_build_object(
      'ok', false, 'code', 'invalid_credentials',
      'error', 'Invalid username or password');
  end if;

  if not v_user.is_active then
    return jsonb_build_object(
      'ok', false, 'code', 'disabled',
      'error', 'This account has been disabled');
  end if;

  -- Note: failures return instead of raising so the counter update below is not
  -- rolled back.
  --
  -- There is deliberately no lockout: a wrong password can be retried any
  -- number of times. failed_attempts is a diagnostic counter only and never
  -- blocks a sign-in.
  if v_user.password_hash <> extensions.crypt(p_password, v_user.password_hash) then
    update public.app_users
       set failed_attempts = failed_attempts + 1,
           updated_at = now()
     where id = v_user.id;

    return jsonb_build_object(
      'ok', false, 'code', 'invalid_credentials',
      'error', 'Invalid username or password');
  end if;

  update public.app_users
     set failed_attempts = 0,
         locked_until = null,
         last_login_at = now(),
         updated_at = now()
   where id = v_user.id;

  v_token := encode(extensions.gen_random_bytes(32), 'hex');

  insert into public.app_sessions (user_id, token_hash, expires_at, user_agent)
  values (
    v_user.id,
    encode(extensions.digest(v_token, 'sha256'), 'hex'),
    now() + interval '7 days',
    nullif(current_setting('request.headers', true), '')::json ->> 'user-agent'
  );

  return jsonb_build_object(
    'ok', true,
    'token', v_token,
    'user', jsonb_build_object(
      'id', v_user.id,
      'username', v_user.username,
      'name', v_user.name,
      'role', v_user.role,
      'mustChangePassword', v_user.must_change_password
    )
  );
end;
$$;

create or replace function public.app_logout()
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  update public.app_sessions
     set revoked_at = now()
   where token_hash = app.request_token_hash()
     and revoked_at is null;
end;
$$;

create or replace function public.app_me()
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_id   bigint := app.session_user_id();
  v_user public.app_users;
begin
  if v_id is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  select * into v_user
    from public.app_users
   where id = v_id and is_active;

  if not found then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  -- Sliding expiry: an active session stays valid for 7 days after last use.
  update public.app_sessions
     set last_seen_at = now(),
         expires_at = now() + interval '7 days'
   where token_hash = app.request_token_hash()
     and revoked_at is null;

  return jsonb_build_object(
    'id', v_user.id,
    'username', v_user.username,
    'name', v_user.name,
    'role', v_user.role,
    'mustChangePassword', v_user.must_change_password
  );
end;
$$;

create or replace function public.app_change_password(p_current text, p_new text)
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_id   bigint := app.session_user_id();
  v_user public.app_users;
begin
  if v_id is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  select * into v_user from public.app_users where id = v_id;

  if v_user.password_hash <> extensions.crypt(p_current, v_user.password_hash) then
    raise exception 'Current password is incorrect' using errcode = '28000';
  end if;

  perform app.assert_password(p_new);

  update public.app_users
     set password_hash = extensions.crypt(p_new, extensions.gen_salt('bf', 12)),
         password_changed_at = now(),
         must_change_password = false,
         failed_attempts = 0,
         locked_until = null,
         updated_at = now()
   where id = v_id;

  -- Changing the password signs every other device out.
  update public.app_sessions
     set revoked_at = now()
   where user_id = v_id
     and revoked_at is null
     and token_hash <> app.request_token_hash();
end;
$$;

